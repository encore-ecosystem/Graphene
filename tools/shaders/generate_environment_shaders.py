#!/usr/bin/env python3
"""Compile environment shaders into embedded SPIR-V (no runtime tool dependency)."""
from pathlib import Path
import subprocess, struct
root=Path(__file__).resolve().parents[2]
out=root/'target/generated-shaders';out.mkdir(parents=True,exist_ok=True)
words=[]
for name,stage,flags in [('environment_sky','frag',()),('environment_precipitation','vert',()),('environment_precipitation','frag',()),('environment_shelter','vert',()),('environment_shelter','frag',()),('environment_sky','frag',('GRAPHENE_CLOUD_ONLY',)),('environment_atmosphere','frag',('GRAPHENE_TRANSMITTANCE_LUT',)),('environment_atmosphere','frag',('GRAPHENE_MULTIPLE_SCATTERING_LUT',)),('environment_atmosphere','frag',()),('environment_cloud_composite','frag',())]:
    symbol=name+'_'+stage+'_'+str(len(words))
    binary=out/(symbol+'.spv')
    subprocess.run(['glslc','-O','--target-env=vulkan1.2',*['-D'+flag for flag in flags],'-I'+str(root/'shaders'),str(root/'shaders'/(name+'.'+stage)),'-o',str(binary)],check=True)
    subprocess.run(['spirv-val','--target-env','vulkan1.2',str(binary)],check=True)
    data=binary.read_bytes();words.append((symbol,struct.unpack('<'+'I'*(len(data)//4),data)))
c='/* Generated by tools/shaders/generate_environment_shaders.py. */\n'
for name,w in words:
    c+='static const uint32_t '+name+'_words[]={\n'
    for i in range(0,len(w),12):c+=','.join(f'0x{x:08x}u' for x in w[i:i+12])+',\n'
    c+='};\n'
c+='uint32_t graphene_environment_shader_word(uint32_t shader,uint32_t index){switch(shader){\n'
for i,(name,w) in enumerate(words):c+=f'case {i}:return index<{len(w)}u?{name}_words[index]:0;\n'
c+='default:return 0;}}\nuint32_t graphene_environment_shader_length(uint32_t shader){switch(shader){\n'
for i,(name,w) in enumerate(words):c+=f'case {i}:return {len(w)}u;\n'
c+='default:return 0;}}\n'
(root/'native/environment_shader_data.c').write_text(c)
