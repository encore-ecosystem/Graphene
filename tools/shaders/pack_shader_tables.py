#!/usr/bin/env python3
"""Keep SPIR-V tables out of Encore IR; public shader functions stay unchanged."""
from pathlib import Path
import re, zlib, json
root=Path(__file__).resolve().parents[2]
tables=root/'native/shaders';tables.mkdir(parents=True,exist_ok=True)
index=tables/'index.json'
entries=json.loads(index.read_text()) if index.exists() else {}
pattern=re.compile(r'pub fn (\w+)\(\) -> Vec\[u32\] \{\s*let mut words = Vec\[u32\]::new\(\)\s*((?:\s*words\.push\(\d+_u32\))+)\s*ret words\s*\}',re.S)
for p in (root/'src/shaders').glob('*.enq'):
 s=p.read_text(); changed=False
 def replace(m):
  global changed
  name=m[1];values=[int(v) for v in re.findall(r'words\.push\((\d+)_u32\)',m[2])]
  key=zlib.crc32(name.encode())
  if any(v['id']==key and n!=name for n,v in entries.items()):raise RuntimeError('shader ID collision')
  entries[name]={'id':key,'count':len(values)}
  c=f'static const uint32_t {name}_words[]={{\n'
  for i in range(0,len(values),12):c+=','.join(f'0x{v:08x}u' for v in values[i:i+12])+',\n'
  (tables/(name+'.inc')).write_text(c+'};\n')
  changed=True
  return f'pub fn {name}() -> Vec[u32] {{\n    ret builtin_spirv({key}_u32)\n}}'
 s=pattern.sub(replace,s)
 if changed:
  s=s.replace('import core::vec::Vec','import core::vec::Vec\nimport mod::builtin::builtin_spirv',1);p.write_text(s)
index.write_text(json.dumps(entries,indent=2,sort_keys=True)+'\n')
c='/* Generated by tools/shaders/pack_shader_tables.py. GLSL sources are authoritative. */\n'
for name in sorted(entries):c+=f'#include "shaders/{name}.inc"\n'
c+='uint32_t graphene_builtin_shader_length(uint32_t shader){switch(shader){\n'
for name,v in sorted(entries.items()):c+=f'case {v["id"]}u:return {v["count"]}u;\n'
c+='default:return 0;}}\nuint32_t graphene_builtin_shader_word(uint32_t shader,uint32_t i){switch(shader){\n'
for name,v in sorted(entries.items()):c+=f'case {v["id"]}u:return i<{v["count"]}u?{name}_words[i]:0;\n'
c+='default:return 0;}}\n'
(root/'native/builtin_shader_data.c').write_text(c)
