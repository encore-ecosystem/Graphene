#!/usr/bin/env python3
"""Cook/validate AA GLSL; native word tables keep generated Encore sources small."""
import pathlib,struct,subprocess
root=pathlib.Path(__file__).resolve().parents[2]
out=root/'target/generated-shaders';out.mkdir(parents=True,exist_ok=True)
shaders=[('aa_fullscreen','aa_fullscreen.vert',())]
for name in ['copy','encode','fxaa','taa','smaa_edge','smaa_weights','smaa_blend']:
    shaders.append(('aa_'+name,'aa_'+name+'.frag',()))
for variant in ['linear','temporal']:
    flags=('GRAPHENE_LINEAR_COLOR','GRAPHENE_ENVIRONMENT_SHELTER')+(('GRAPHENE_TEMPORAL',) if variant=='temporal' else ())
    for stage,file,extra in [('vertex','cube.vert',('GRAPHENE_BASE_COLOR_TEXTURE',)),('fragment','cube.frag',('GRAPHENE_BASE_COLOR_TEXTURE',)),('mesh','virtual_scene.mesh',()),('virtual_fragment','virtual_scene.frag',()),('virtual_triangle','virtual_scene_triangle.frag',())]:
        shaders.append(('aa_'+variant+'_'+stage,file,flags+extra))
# Append new programs so existing material shader IDs remain stable.
shaders.append(('aa_reactive','aa_reactive.frag',()))
compiled=[]
for name,file,flags in shaders:
    binary=out/(name+'.spv')
    subprocess.run(['glslc','-O','--target-env=vulkan1.2',*['-D'+v for v in flags],'-I'+str(root/'shaders'),str(root/'shaders'/file),'-o',str(binary)],check=True)
    subprocess.run(['spirv-val','--target-env','vulkan1.2',str(binary)],check=True)
    data=binary.read_bytes();words=struct.unpack('<'+'I'*(len(data)//4),data)
    compiled.append((name,words))
c='/* Generated by tools/shaders/generate_aa_shaders.py. GLSL sources are authoritative.\n * SMAA copyright/license: shaders/third_party/smaa/LICENSE.txt. */\n'
for name,words in compiled:
    c+='static const uint32_t '+name+'_words[] = {\n'
    for i in range(0,len(words),12):c+='    '+','.join(f'0x{x:08x}u' for x in words[i:i+12])+',\n'
    c+='};\n'
c+='uint32_t graphene_aa_shader_length(uint32_t shader) {switch(shader) {\n'
for i,(name,words) in enumerate(compiled):c+=f'case {i}:return {len(words)}u;\n'
c+='default:return 0;}}\nuint32_t graphene_aa_shader_word(uint32_t shader,uint32_t index) {switch(shader) {\n'
for i,(name,words) in enumerate(compiled):c+=f'case {i}:return index<{len(words)}u?{name}_words[index]:0;\n'
c+='default:return 0;}}\n'
(root/'native/aa_shader_data.c').write_text(c)
for i,(name,words) in enumerate(compiled):
    (root/'src/shaders'/f'{name}.enq').write_text('import core::vec::Vec\nimport mod::aa_data::aa_spirv\n\npub fn '+name+'() -> Vec[u32] {\n    ret aa_spirv('+str(i)+'_u32)\n}\n')
