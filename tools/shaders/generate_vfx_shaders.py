#!/usr/bin/env python3
"""Build portable VFX kernels once; cooked games need no shader compiler."""
from pathlib import Path
import struct,subprocess
root=Path(__file__).resolve().parents[2]
out=root/'target/vfx';out.mkdir(exist_ok=True,parents=True)
names=['simulate.comp','particle.vert','particle.frag','fluid.comp','fluid.frag','fullscreen.vert']
s='/* Generated by tools/shaders/generate_vfx_shaders.py. */\n'
for i,name in enumerate(names):
 p=out/(name+'.spv')
 subprocess.run(['glslc','-O','--target-env=vulkan1.2','-I'+str(root/'shaders/vfx'),str(root/'shaders/vfx'/name),'-o',str(p)],check=True)
 subprocess.run(['spirv-val','--target-env','vulkan1.2',str(p)],check=True)
 words=struct.unpack('<'+'I'*(p.stat().st_size//4),p.read_bytes())
 s+=f'static const uint32_t gvfx_shader_{i}[]={{\n'
 for j in range(0,len(words),12):s+=','.join(f'0x{v:08x}u' for v in words[j:j+12])+',\n'
 s+='};\n'
s+='uint32_t graphene_vfx_shader_length(uint32_t s){switch(s){'+''.join(f'case {i}:return sizeof(gvfx_shader_{i})/4;' for i in range(len(names)))+'default:return 0;}}\n'
s+='uint32_t graphene_vfx_shader_word(uint32_t s,uint32_t w){if(w>=graphene_vfx_shader_length(s))return 0;switch(s){'+''.join(f'case {i}:return gvfx_shader_{i}[w];' for i in range(len(names)))+'default:return 0;}}\n'
(root/'native/vfx/shaders.c').write_text(s)
